function A = audit_shipped_data (outdir)
  ## -*- texinfo -*-
  ## @deftypefn {} {@var{A} =} audit_shipped_data ()
  ## @deftypefnx {} {@var{A} =} audit_shipped_data (@var{outdir})
  ## Audit whether the CSV files in @file{flagship_project/datasets} can
  ## support a supervised failure-prediction model, before any modelling.
  ##
  ## Checks: row counts, time coverage of each table, which equipment has
  ## sensor data, and -- decisively -- how many failure events fall inside
  ## the sensor observation window of the same equipment (plus a 72 h
  ## look-ahead horizon).  With zero such events there are no positive
  ## labels, and no predictive claim is identifiable from these data,
  ## whatever the model.
  ##
  ## Writes @file{data_audit.md} to @var{outdir} (default
  ## flagship_project/results) and returns the findings as a struct.
  ## @end deftypefn

  here = fileparts (mfilename ("fullpath"));
  root = fileparts (fileparts (here));
  addpath (fullfile (root, "inst"));
  ddir = fullfile (root, "flagship_project", "datasets");
  if (nargin < 1)
    outdir = fullfile (root, "flagship_project", "results");
  endif
  if (! exist (outdir, "dir"))
    mkdir (outdir);
  endif

  S = omp.io.read_csv (fullfile (ddir, "sensor_network_data.csv"));
  Fe = omp.io.read_csv (fullfile (ddir, "failure_events.csv"));
  M = omp.io.read_csv (fullfile (ddir, "maintenance_logs.csv"));
  E = omp.io.read_csv (fullfile (ddir, "equipment_metadata.csv"));

  ts = datenum (S.Timestamp, "yyyy-mm-dd HH:MM:SS");
  tf = datenum (strcat (Fe.Failure_Date, {" "}, Fe.Failure_Time), "yyyy-mm-dd HH:MM:SS");
  tm = datenum (M.Maintenance_Date, "yyyy-mm-dd");
  horizon_days = 72 / 24;

  A = struct ();
  A.n_sensor_rows = numel (ts);
  A.n_failures = numel (tf);
  A.n_maintenance = numel (tm);
  A.n_equipment = numel (E.Equipment_ID);
  A.sensor_range = {datestr(min (ts), 31), datestr(max (ts), 31)};
  A.failure_range = {datestr(min (tf), 31), datestr(max (tf), 31)};
  A.maintenance_range = {datestr(min (tm), 31), datestr(max (tm), 31)};
  A.sensor_hours = (max (ts) - min (ts)) * 24;

  eq = unique (S.Equipment_ID);
  A.sensor_equipment = eq';
  A.per_equipment = struct ("id", {}, "readings", {}, "failures_total", {}, ...
                            "failures_in_window", {});
  total_in = 0;
  for i = 1:numel (eq)
    k = strcmp (S.Equipment_ID, eq{i});
    lo = min (ts(k));
    hi = max (ts(k)) + horizon_days;
    kf = strcmp (Fe.Equipment_ID, eq{i});
    nin = sum (kf & tf >= lo & tf <= hi);
    total_in += nin;
    A.per_equipment(end+1) = struct ("id", eq{i}, "readings", sum (k), ...
                                     "failures_total", sum (kf), ...
                                     "failures_in_window", nin);
  endfor
  A.failures_in_sensor_windows = total_in;
  A.identifiable = total_in > 0;

  fid = fopen (fullfile (outdir, "data_audit.md"), "w");
  fprintf (fid, "# Audit of the shipped flagship datasets\n\n");
  fprintf (fid, "Generated by `flagship_project/experiment/audit_shipped_data.m`.\n\n");
  fprintf (fid, "| Table | Rows | Time coverage |\n|---|---|---|\n");
  fprintf (fid, "| sensor_network_data | %d | %s → %s (%.0f h) |\n", A.n_sensor_rows, ...
           A.sensor_range{:}, A.sensor_hours);
  fprintf (fid, "| failure_events | %d | %s → %s |\n", A.n_failures, A.failure_range{:});
  fprintf (fid, "| maintenance_logs | %d | %s → %s |\n", A.n_maintenance, A.maintenance_range{:});
  fprintf (fid, "| equipment_metadata | %d | – |\n\n", A.n_equipment);
  fprintf (fid, "| Equipment with sensors | Readings | Failures (all time) | Failures in sensor window + 72 h |\n|---|---|---|---|\n");
  for i = 1:numel (A.per_equipment)
    p = A.per_equipment(i);
    fprintf (fid, "| %s | %d | %d | %d |\n", p.id, p.readings, p.failures_total, ...
             p.failures_in_window);
  endfor
  fprintf (fid, "\n**Failure events overlapping sensor coverage: %d.**\n\n", total_in);
  if (A.identifiable)
    fprintf (fid, "Some positive labels exist; modelling is possible but sample size is tiny.\n");
  else
    fprintf (fid, ["With no failure observed while sensors were recording, every ", ...
                   "label in the sensor window is negative. A failure-prediction model ", ...
                   "trained or evaluated on these files would have no positive examples, ", ...
                   "so any reported predictive performance would be an artefact. ", ...
                   "The flagship study therefore uses a simulator with known ground ", ...
                   "truth (`run_pdm_experiment.m`); these files remain useful only for ", ...
                   "demonstrating data handling.\n"]);
  endif
  fclose (fid);
  printf ("Failure events inside sensor coverage: %d (identifiable: %d)\n", ...
          total_in, A.identifiable);
endfunction
